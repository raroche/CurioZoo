export const gt = (key, lang, vars) => lookup(GATES_TEXT, key, lang, vars);

/** "the lion" / "del león" for a lamp's owner. */
export function lampOwner(animal, L) {
  return L === 'es' ? `${animal.es.art === 'la' ? 'de la' : 'del'} ${animal.es.n}` : animal.en;
}

