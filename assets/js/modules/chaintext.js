export const ct = (key, lang, vars) => lookup(CHAIN_TEXT, key, lang, vars);

const cap1 = (x) => x.charAt(0).toUpperCase() + x.slice(1);

/** "the zebra" / "la cebra"; the Sun and soil too. */
export function the(id, L, cap = false) {
  const name = CHAIN_TEXT[L === 'es' ? 'es' : 'en'][`sp.${id}`] || id;
  const text = L === 'es' ? name : `the ${name}`;
  return cap ? cap1(text) : text;
}

/** Spanish "a" and "de" before a name with its article: "al león", "a la cebra", "del pasto". */
export const aThe = (id, L) => (L === 'es' ? `a ${the(id, L)}`.replace(/^a el /, 'al ') : the(id, L));
export const deThe = (id, L) => (L === 'es' ? `de ${the(id, L)}`.replace(/^de el /, 'del ') : the(id, L));

/** Every name slot a sentence may use, for a food `a` and an eater `b`. */
export const pair = (a, b, L) => ({ a: the(a, L), A: the(a, L, true), b: the(b, L), ab: aThe(b, L), da: deThe(a, L) });

export default { CHAIN_TEXT, ct, the, aThe, deThe };
